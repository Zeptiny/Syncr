// The text of the generated types file and of the virtual modules.

import { compareCodeUnits, type DocsModel, type NavItem, type Page } from "./model.ts";
import { GITHUB_REF_TOKEN, IMAGE_PLACEHOLDER_RE } from "./render.ts";

export const MANIFEST_ID = "virtual:syncr-docs/manifest";
export const SEARCH_ID = "virtual:syncr-docs/search";
export const PAGE_PREFIX = "virtual:syncr-docs/page/";

/** The module key of a page: its slug, "README" for the index (slug ""). */
export function pageKey(slug: string): string {
  return slug === "" ? "README" : slug;
}

export function slugFromKey(key: string): string {
  return key === "README" ? "" : key;
}

const str = (value: string): string => JSON.stringify(value);

export function genFileText(model: DocsModel): string {
  const pages = [...model.pages].sort((a, b) => compareCodeUnits(a.slug, b.slug));
  const out = [
    "// Generated by docs-plugin from docs/. Run `npm run generate:docs`; do not edit.",
    "",
    "/** The heading IDs (H2 and deeper) of each page shipped in the app. */",
    "export interface DocAnchors {",
  ];
  for (const page of pages) {
    if (page.headings.length === 0) {
      out.push(`  ${str(page.slug)}: never;`);
      continue;
    }
    out.push(`  ${str(page.slug)}:`);
    page.headings.forEach((h, i) => {
      out.push(`    | ${str(h.id)}${i === page.headings.length - 1 ? ";" : ""}`);
    });
  }
  out.push(
    "}",
    "",
    '/** A page shipped in the app: its path in docs/ without .md ("" is the index). */',
  );
  out.push(
    "export type DocPage = keyof DocAnchors;",
    "",
    "export const DOC_TITLES: Record<DocPage, string> = {",
  );
  for (const page of pages) out.push(`  ${str(page.slug)}: ${str(page.title)},`);
  out.push("};", "");
  return out.join("\n");
}

const navItem = (item: NavItem): Record<string, unknown> => ({
  label: item.label,
  ...(item.slug !== undefined ? { slug: item.slug } : {}),
  ...(item.external !== undefined ? { external: item.external } : {}),
  ...(item.children ? { children: item.children.map(navItem) } : {}),
});

export function manifestModule(model: DocsModel): string {
  const data = {
    title: model.title,
    githubRepo: model.githubRepo,
    githubRefToken: GITHUB_REF_TOKEN,
    groups: model.groups.map((g) => ({ title: g.title, items: g.items.map(navItem) })),
    pages: model.pages.map((p) => ({ slug: p.slug, title: p.title, file: p.file })),
  };
  const loaders = model.pages.map(
    (p) => `    ${str(p.slug)}: () => import(${str(PAGE_PREFIX + pageKey(p.slug))}),`,
  );
  const json = JSON.stringify(data, null, 2);
  return [
    `const manifest = ${json};`,
    "manifest.loaders = {",
    ...loaders,
    "};",
    "export default manifest;",
    "",
  ].join("\n");
}

/** A page module; importPath maps a repository-relative image to its import specifier. */
export function pageModule(page: Page, importPath: (file: string) => string): string {
  const imports = page.images.map((file, i) => `import i${i} from ${str(importPath(file))};`);
  const pieces: string[] = [];
  let last = 0;
  for (const m of page.html.matchAll(IMAGE_PLACEHOLDER_RE)) {
    pieces.push(str(page.html.slice(last, m.index)), `i${m[1]}`);
    last = m.index + m[0].length;
  }
  pieces.push(str(page.html.slice(last)));
  const headings = page.headings
    .filter((h) => h.depth === 2 || h.depth === 3)
    .map((h) => ({ depth: h.depth, id: h.id, text: h.text }));
  return [
    ...imports,
    "export default {",
    `  title: ${str(page.title)},`,
    `  html: ${pieces.join(" + ")},`,
    `  headings: ${JSON.stringify(headings)},`,
    "};",
    "",
  ].join("\n");
}

export function searchModule(model: DocsModel): string {
  return `export default ${JSON.stringify(model.search)};\n`;
}
