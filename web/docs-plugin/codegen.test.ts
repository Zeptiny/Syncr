// @vitest-environment node
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

import type { Plugin } from "vite";
import { afterEach, describe, expect, it } from "vitest";

import { genFileText, manifestModule, pageModule, searchModule } from "./codegen.ts";
import { syncrDocs } from "./index.ts";
import { buildDocs } from "./model.ts";
import { TESTDATA_ROOT, testOptions } from "./testing.ts";

const { model } = buildDocs(testOptions(TESTDATA_ROOT));

describe("codegen", () => {
  it("writes the types file, stable and sorted", () => {
    expect(genFileText(model)).toBe(
      [
        "// Generated by docs-plugin from docs/. Run `npm run generate:docs`; do not edit.",
        "",
        "/** The heading IDs (H2 and deeper) of each page shipped in the app. */",
        "export interface DocAnchors {",
        '  "":',
        '    | "start"',
        '    | "reference"',
        '    | "on-github";',
        '  "guide":',
        '    | "first-steps"',
        '    | "ftp--ftps"',
        '    | "first-steps-1";',
        '  "other":',
        '    | "the-details"',
        '    | "deeper"',
        '    | "deepest";',
        '  "releases": never;',
        '  "releases/v1.0.0":',
        '    | "known-limitations";',
        "}",
        "",
        '/** A page shipped in the app: its path in docs/ without .md ("" is the index). */',
        "export type DocPage = keyof DocAnchors;",
        "",
        "export const DOC_TITLES: Record<DocPage, string> = {",
        '  "": "Test docs",',
        '  "guide": "The guide",',
        '  "other": "Other page",',
        '  "releases": "Releases",',
        '  "releases/v1.0.0": "Release 1.0.0",',
        "};",
        "",
      ].join("\n"),
    );
    expect(genFileText(buildDocs(testOptions(TESTDATA_ROOT)).model)).toBe(genFileText(model));
  });

  it("writes the manifest with one lazy loader per page", () => {
    const code = manifestModule(model);
    expect(code).toContain('"": () => import("virtual:syncr-docs/page/README"),');
    expect(code).toContain(
      '"releases/v1.0.0": () => import("virtual:syncr-docs/page/releases/v1.0.0"),',
    );
    expect(code).toContain('"githubRefToken": "__SYNCR_GITHUB_REF__"');
    expect(code).toMatch(/export default manifest;\n$/);
  });

  it("imports each image of a page and joins it into the HTML", () => {
    const guide = model.pages.find((p) => p.slug === "guide");
    if (!guide) throw new Error("no guide");
    const code = pageModule(guide, (file) => `/abs/${file}`);
    expect(code).toMatch(
      /^import i0 from "\/abs\/docs\/img\/shot\.png";\nimport i1 from "\/abs\/docs\/img\/diagram\.svg";\n/,
    );
    expect(code).toContain('<img src=\\"" + i0 + "\\" alt=\\"A screenshot of the form\\"');
    expect(code).toContain(
      'headings: [{"depth":2,"id":"first-steps","text":"First steps"},{"depth":2,"id":"ftp--ftps","text":"FTP & FTPS"},' +
        '{"depth":2,"id":"first-steps-1","text":"First steps"}],',
    );
    expect(code).not.toContain("\x00");
  });

  it("builds the search index from sections at H2 and H3", () => {
    expect(model.search.pages).toEqual([
      { slug: "guide", title: "The guide" },
      { slug: "other", title: "Other page" },
      { slug: "releases", title: "Releases" },
      { slug: "releases/v1.0.0", title: "Release 1.0.0" },
    ]);
    expect(model.search.sections).toContainEqual([
      0,
      "",
      "",
      "Intro with a same page link and another page.",
    ]);
    expect(model.search.sections).toContainEqual([
      0,
      "ftp--ftps",
      "FTP & FTPS",
      'echo "a < b" plain Name Value one 1',
    ]);
    expect(model.search.sections).toContainEqual([1, "deeper", "Deeper", "More. Deepest End."]);
    expect(searchModule(model)).toBe(`export default ${JSON.stringify(model.search)};\n`);
  });
});

describe("the plugin", () => {
  const tmpDirs: string[] = [];
  afterEach(() => {
    for (const dir of tmpDirs.splice(0)) fs.rmSync(dir, { recursive: true, force: true });
  });

  type Hook = (this: unknown, ...args: unknown[]) => unknown;
  const hook = (plugin: Plugin, name: keyof Plugin): Hook => plugin[name] as Hook;
  const context = {
    error(message: string): never {
      throw new Error(message);
    },
    warn(): void {},
  };

  function start(command: "build" | "serve"): { plugin: Plugin; root: string; genFile: string } {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), "docs-plugin-"));
    tmpDirs.push(root);
    const plugin = syncrDocs(testOptions(TESTDATA_ROOT));
    hook(plugin, "configResolved").call(context, { command, root });
    return { plugin, root, genFile: path.join(root, "src", "docs.gen.ts") };
  }

  it("fails a build when the types file is out of date", () => {
    const { plugin, genFile } = start("build");
    expect(() => hook(plugin, "buildStart").call(context)).toThrow(
      "src/docs.gen.ts is out of date: run npm run generate:docs",
    );
    fs.mkdirSync(path.dirname(genFile), { recursive: true });
    fs.writeFileSync(genFile, genFileText(model));
    expect(() => hook(plugin, "buildStart").call(context)).not.toThrow();
  });

  it("writes the types file in serve mode and serves the virtual modules", () => {
    const { plugin, genFile } = start("serve");
    hook(plugin, "buildStart").call(context);
    expect(fs.readFileSync(genFile, "utf8")).toBe(genFileText(model));
    const resolve = hook(plugin, "resolveId");
    const load = hook(plugin, "load");
    expect(resolve.call(context, "virtual:syncr-docs/manifest")).toBe(
      "\0virtual:syncr-docs/manifest",
    );
    expect(resolve.call(context, "./other")).toBeUndefined();
    expect(load.call(context, "\0virtual:syncr-docs/manifest")).toBe(manifestModule(model));
    expect(load.call(context, "\0virtual:syncr-docs/search")).toBe(searchModule(model));
    expect(load.call(context, "\0virtual:syncr-docs/page/README")).toContain('title: "Test docs"');
    expect(load.call(context, "\0virtual:syncr-docs/page/releases/v1.0.0")).toContain(
      'title: "Release 1.0.0"',
    );
    expect(() => load.call(context, "\0virtual:syncr-docs/page/missing")).toThrow(
      'no docs page "missing"',
    );
  });

  it("names page chunks after the page", () => {
    const config = (hook(syncrDocs(testOptions(TESTDATA_ROOT)), "config").call(context) ?? {}) as {
      build: {
        rolldownOptions: {
          output: {
            chunkFileNames: (c: { facadeModuleId: string | null; moduleIds: string[] }) => string;
          };
        };
      };
    };
    const chunkFileNames = config.build.rolldownOptions.output.chunkFileNames;
    const name = (facadeModuleId: string | null, moduleIds: string[] = []) =>
      chunkFileNames({
        facadeModuleId,
        moduleIds: facadeModuleId ? [facadeModuleId, ...moduleIds] : moduleIds,
      });
    expect(name("\0virtual:syncr-docs/page/releases/v1.0.0")).toBe(
      "assets/doc-releases-v1.0.0-[hash].js",
    );
    expect(name("\0virtual:syncr-docs/search")).toBe("assets/doc-search-[hash].js");
    // The manifest is merged into the chunk of manifest.ts, which imports it.
    expect(name("/web/src/features/docs/manifest.ts", ["\0virtual:syncr-docs/manifest"])).toBe(
      "assets/doc-manifest-[hash].js",
    );
    expect(name(null)).toBe("assets/[name]-[hash].js");
    expect(name("/web/src/main.tsx")).toBe("assets/[name]-[hash].js");
  });
});
